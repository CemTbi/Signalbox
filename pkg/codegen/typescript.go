// runtime is the part of every TypeScript client that doesn't depend on
// the API: building URLs and requests, and reading responses.
//
//go:embed typescript_runtime.ts
var tsRuntime string

// typescript writes a TypeScript client: a type per component schema, and a
// client with a method per operation, on fetch. It has no dependencies.
func typescript(spec *openapi3.T) string {
	g := &tsGen{spec: spec, names: map[string]string{}}
	g.nameSchemas()

	var b strings.Builder
	title, version := "the API", ""
	if spec.Info != nil {
		title, version = spec.Info.Title, spec.Info.Version
	}
	fmt.Fprintf(&b, "// A client for %s%s, generated by Signalbox. Don't edit this file:\n", oneLine(title), prefixed(" ", oneLine(version)))
	b.WriteString("// generate it again when the API changes.\n\n/* eslint-disable */\n\n")

	// Types for the component schemas, in name order.
	for _, key := range g.schemaKeys {
		ref := spec.Components.Schemas[key]
		if ref == nil || ref.Value == nil {
			continue
		}
		g.doc(&b, "", ref.Value.Title, ref.Value.Description, ref.Value.Deprecated)
		fmt.Fprintf(&b, "export type %s = %s;\n\n", g.names[key], g.typeOf(ref, ""))
	}

	b.WriteString(tsRuntime)
	b.WriteString("\n")

	ops := g.operations()
	b.WriteString("/** Creates a client for the API. */\n")
	b.WriteString("export function createClient(options: ClientOptions) {\n")
	b.WriteString("  const call = caller(options);\n")
	b.WriteString("  return {\n")
	for _, op := range ops {
		g.method(&b, op)
	}
	b.WriteString("  };\n}\n\n")
	b.WriteString("/** A client for the API, as createClient returns it. */\n")
	b.WriteString("export type Client = ReturnType<typeof createClient>;\n")
	return b.String()
}

type tsGen struct {
	spec       *openapi3.T
	names      map[string]string // component schema key to type name
	schemaKeys []string
	// expanding holds the schemas being written inline, so a schema that
	// contains itself without a component reference doesn't recurse
	// forever.
	expanding []*openapi3.Schema
}

const componentPrefix = "#/components/schemas/"

func (g *tsGen) nameSchemas() {
	if g.spec.Components == nil {
		return
	}
	for key := range g.spec.Components.Schemas {
		g.schemaKeys = append(g.schemaKeys, key)
	}
	sort.Strings(g.schemaKeys)
	used := map[string]bool{}
	for _, name := range tsReserved {
		used[name] = true
	}
	for _, key := range g.schemaKeys {
		name := pascal(key)
		if name == "" || !unicode.IsLetter(rune(name[0])) {
			name = "Schema" + name
		}
		for base, n := name, 2; used[name]; n++ {
			name = fmt.Sprintf("%s%d", base, n)
		}
		used[name] = true
		g.names[key] = name
	}
}

// tsReserved are names a schema's type can't take: those the runtime and
// the client declare, and the global types they use, which a type of the
// same name would shadow.
var tsReserved = []string{
	"ApiError", "Call", "Client", "ClientOptions", "Fetch", "RequestOptions",
	"AbortSignal", "Array", "ArrayBuffer", "Blob", "BodyInit", "Boolean", "Date", "Error", "FormData", "Headers",
	"HeadersInit", "JSON", "Map", "Number", "Object", "Promise", "Record", "RequestInit", "Response",
	"ReturnType", "Set", "String", "Uint8Array", "URLSearchParams",
}

// typeOf writes a schema as a TypeScript type. indent is the indentation
// of the line the type starts on.
func (g *tsGen) typeOf(ref *openapi3.SchemaRef, indent string) string {
	if ref == nil {
		return "unknown"
	}
	if name, ok := strings.CutPrefix(ref.Ref, componentPrefix); ok {
		if n, ok := g.names[name]; ok {
			return n
		}
	}
	s := ref.Value
	if s == nil {
		return "unknown"
	}
	for _, e := range g.expanding {
		if e == s {
			return "unknown"
		}
	}
	g.expanding = append(g.expanding, s)
	defer func() { g.expanding = g.expanding[:len(g.expanding)-1] }()

	t := g.bareType(s, indent)
	if s.Nullable || (s.Type != nil && s.Type.IncludesNull()) {
		if t != "null" && t != "unknown" {
			t += " | null"
		}
	}
	return t
}

func (g *tsGen) bareType(s *openapi3.Schema, indent string) string {
	if len(s.Enum) > 0 {
		var vals []string
		for _, v := range s.Enum {
			if v == nil {
				continue
			}
			vals = append(vals, literal(v))
		}
		if len(vals) > 0 {
			return strings.Join(vals, " | ")
		}
	}
	if s.Const != nil {
		return literal(s.Const)
	}
	switch {
	case len(s.OneOf) > 0:
		return g.union(s.OneOf, " | ", indent)
	case len(s.AnyOf) > 0:
		return g.union(s.AnyOf, " | ", indent)
	case len(s.AllOf) > 0:
		parts := g.union(s.AllOf, " & ", indent)
		if len(s.Properties) > 0 {
			return parts + " & " + g.object(s, indent)
		}
		return parts
	}
	var types []string
	if s.Type != nil {
		for _, t := range s.Type.Slice() {
			if t != "null" {
				types = append(types, t)
			}
		}
	}
	if len(types) == 0 {
		switch {
		case len(s.Properties) > 0 || s.AdditionalProperties.Schema != nil:
			types = []string{"object"}
		case s.Items != nil:
			types = []string{"array"}
		case s.Type != nil && s.Type.IncludesNull():
			return "null"
		default:
			return "unknown"
		}
	}
	var out []string
	for _, t := range types {
		switch t {
		case "string":
			if s.Format == "binary" {
				out = append(out, "Blob")
			} else {
				out = append(out, "string")
			}
		case "integer", "number":
			out = append(out, "number")
		case "boolean":
			out = append(out, "boolean")
		case "array":
			item := g.typeOf(s.Items, indent)
			if strings.ContainsAny(item, " |&") && !strings.HasPrefix(item, "{") {
				item = "(" + item + ")"
			}
			out = append(out, item+"[]")
		case "object":
			out = append(out, g.object(s, indent))
		default:
			out = append(out, "unknown")
		}
	}
	return strings.Join(out, " | ")
}

func (g *tsGen) union(refs openapi3.SchemaRefs, sep, indent string) string {
	parts := make([]string, 0, len(refs))
	for _, r := range refs {
		t := g.typeOf(r, indent)
		if strings.Contains(t, " | ") && sep == " & " {
			t = "(" + t + ")"
		}
		parts = append(parts, t)
	}
	return strings.Join(parts, sep)
}

// object writes an object type, with a line per property.
func (g *tsGen) object(s *openapi3.Schema, indent string) string {
	extra := s.AdditionalProperties
	if len(s.Properties) == 0 {
		switch {
		case extra.Schema != nil:
			return "{ [key: string]: " + g.typeOf(extra.Schema, indent) + " }"
		case extra.Has != nil && !*extra.Has:
			return "Record<string, never>"
		}
		return "{ [key: string]: unknown }"
	}
	required := map[string]bool{}
	for _, r := range s.Required {
		required[r] = true
	}
	names := make([]string, 0, len(s.Properties))
	for name := range s.Properties {
		names = append(names, name)
	}
	sort.Strings(names)
	inner := indent + "  "
	var b strings.Builder
	b.WriteString("{\n")
	for _, name := range names {
		p := s.Properties[name]
		if p != nil && p.Value != nil {
			var docs strings.Builder
			g.doc(&docs, inner, p.Value.Title, p.Value.Description, p.Value.Deprecated)
			b.WriteString(docs.String())
		}
		opt := "?"
		if required[name] {
			opt = ""
		}
		fmt.Fprintf(&b, "%s%s%s: %s;\n", inner, key(name), opt, g.typeOf(p, inner))
	}
	if extra.Schema != nil {
		fmt.Fprintf(&b, "%s[key: string]: unknown;\n", inner)
	}
	b.WriteString(indent + "}")
	return b.String()
}

// doc writes a JSDoc comment, if there's anything to say.
func (g *tsGen) doc(b *strings.Builder, indent, title, description string, deprecated bool) {
	var lines []string
	for _, text := range []string{title, description} {
		text = strings.TrimSpace(text)
		if text == "" || (len(lines) > 0 && text == lines[0]) {
			continue
		}
		lines = append(lines, strings.Split(text, "\n")...)
	}
	if deprecated {
		lines = append(lines, "@deprecated")
	}
	if len(lines) == 0 {
		return
	}
	b.WriteString(indent + "/**\n")
	for _, l := range lines {
		l = strings.ReplaceAll(strings.TrimRight(l, " \t\r"), "*/", "*\\/")
		if l == "" {
			b.WriteString(indent + " *\n")
		} else {
			b.WriteString(indent + " * " + l + "\n")
		}
	}
	b.WriteString(indent + " */\n")
}

type tsOperation struct {
	name   string
	method string
	path   string
	op     *openapi3.Operation
	params []*openapi3.Parameter
}

var methodOrder = []string{"GET", "PUT", "POST", "DELETE", "OPTIONS", "HEAD", "PATCH", "TRACE"}

// operations lists the operations in path and method order, each with a
// unique method name.
func (g *tsGen) operations() []tsOperation {
	var out []tsOperation
	if g.spec.Paths == nil {
		return out
	}
	used := map[string]bool{}
	for _, name := range []string{"constructor", "toString"} {
		used[name] = true
	}
	paths := g.spec.Paths.Map()
	keys := make([]string, 0, len(paths))
	for k := range paths {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, path := range keys {
		item := paths[path]
		if item == nil {
			continue
		}
		for _, method := range methodOrder {
			op := item.GetOperation(method)
			if op == nil {
				continue
			}
			name := camel(op.OperationID)
			if name == "" {
				name = camel(strings.ToLower(method) + " " + pathWords(path))
			}
			if name == "" || !unicode.IsLetter(rune(name[0])) {
				name = "call" + pascal(name)
			}
			for base, n := name, 2; used[name]; n++ {
				name = fmt.Sprintf("%s%d", base, n)
			}
			used[name] = true
			out = append(out, tsOperation{name: name, method: method, path: path, op: op, params: mergeParams(item.Parameters, op.Parameters)})
		}
	}
	return out
}

// mergeParams puts an operation's parameters over its path item's, with
// cookies left out: browsers don't let scripts set them.
func mergeParams(item, op openapi3.Parameters) []*openapi3.Parameter {
	seen := map[string]bool{}
	var out []*openapi3.Parameter
	for _, list := range []openapi3.Parameters{op, item} {
		for _, p := range list {
			if p == nil || p.Value == nil || p.Value.In == "cookie" || seen[p.Value.In+" "+p.Value.Name] {
				continue
			}
			seen[p.Value.In+" "+p.Value.Name] = true
			out = append(out, p.Value)
		}
	}
	order := map[string]int{"path": 0, "query": 1, "header": 2}
	sort.SliceStable(out, func(i, j int) bool { return order[out[i].In] < order[out[j].In] })
	return out
}

// pathWords turns /orders/{id}/lines into "orders by id lines".
func pathWords(path string) string {
	var words []string
	for _, seg := range strings.Split(path, "/") {
		if seg == "" {
			continue
		}
		if strings.HasPrefix(seg, "{") {
			words = append(words, "by", strings.Trim(seg, "{}"))
		} else {
			words = append(words, seg)
		}
	}
	return strings.Join(words, " ")
}

// method writes one operation as a method of the client.
func (g *tsGen) method(b *strings.Builder, o tsOperation) {
	op := o.op
	// The parameters object: one property per parameter, then the body.
	var fields []string
	fieldNames := map[string]bool{"body": true}
	type wire struct{ field, name, in, style string }
	var wires []wire
	anyRequired := false
	for _, p := range o.params {
		field := p.Name
		if fieldNames[field] {
			field = p.Name + pascal(p.In)
		}
		fieldNames[field] = true
		opt := "?"
		if p.Required || p.In == "path" {
			opt = ""
			anyRequired = true
		}
		schema := p.Schema
		if schema == nil {
			for _, mt := range p.Content {
				schema = mt.Schema
				break
			}
		}
		var docs strings.Builder
		g.doc(&docs, "      ", "", p.Description, p.Deprecated)
		fields = append(fields, docs.String()+fmt.Sprintf("      %s%s: %s;\n", key(field), opt, g.typeOf(schema, "      ")))
		style := "form"
		if p.Explode != nil && !*p.Explode {
			style = "csv"
		}
		wires = append(wires, wire{field, p.Name, p.In, style})
	}

	bodyType, bodyKind := "", ""
	if rb := op.RequestBody; rb != nil && rb.Value != nil {
		mediaType, media := pickMedia(rb.Value.Content)
		if media != nil {
			bodyKind = bodyKindOf(mediaType)
			bodyType = g.bodyType(bodyKind, media)
			opt := "?"
			if rb.Value.Required {
				opt = ""
				anyRequired = true
			}
			var docs strings.Builder
			g.doc(&docs, "      ", "", rb.Value.Description, false)
			fields = append(fields, docs.String()+fmt.Sprintf("      body%s: %s;\n", opt, bodyType))
			bodyType = mediaType
		}
	}

	result, accept := g.resultType(op)
	summary := op.Summary
	if summary == "" {
		summary = o.method + " " + o.path
	}
	g.doc(b, "    ", summary, op.Description, op.Deprecated)

	paramsArg := ""
	if len(fields) > 0 {
		q := "?"
		if anyRequired {
			q = ""
		}
		paramsArg = "params" + q + ": {\n" + strings.Join(fields, "") + "    }, "
	}
	fmt.Fprintf(b, "    %s(%soptions?: RequestOptions): Promise<%s> {\n", o.name, paramsArg, result)
	if len(fields) > 0 && !anyRequired {
		b.WriteString("      params = params ?? {};\n")
	}
	fmt.Fprintf(b, "      return call(%s, %s, {\n", literal(o.method), literal(o.path))
	var pathParts, queryParts, headerParts []string
	for _, w := range wires {
		v := "params" + accessor(w.field)
		switch w.in {
		case "path":
			pathParts = append(pathParts, fmt.Sprintf("%s: %s", key(w.name), v))
		case "query":
			queryParts = append(queryParts, fmt.Sprintf("[%s, %s, %s]", literal(w.name), v, literal(w.style)))
		case "header":
			headerParts = append(headerParts, fmt.Sprintf("[%s, %s]", literal(w.name), v))
		}
	}
	if len(pathParts) > 0 {
		fmt.Fprintf(b, "        path: { %s },\n", strings.Join(pathParts, ", "))
	}
	if len(queryParts) > 0 {
		fmt.Fprintf(b, "        query: [%s],\n", strings.Join(queryParts, ", "))
	}
	if len(headerParts) > 0 {
		fmt.Fprintf(b, "        headers: [%s],\n", strings.Join(headerParts, ", "))
	}
	if bodyKind != "" {
		fmt.Fprintf(b, "        body: params.body,\n        bodyType: %s,\n        bodyKind: %s,\n", literal(bodyType), literal(bodyKind))
	}
	fmt.Fprintf(b, "        accept: %s,\n", literal(accept))
	b.WriteString("      }, options);\n")
	b.WriteString("    },\n")
}

// pickMedia chooses the media type the client sends or reads: JSON if the
// API has it, then the first in name order.
func pickMedia(content openapi3.Content) (string, *openapi3.MediaType) {
	keys := make([]string, 0, len(content))
	for k := range content {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		if isJSONType(k) {
			return k, content[k]
		}
	}
	if len(keys) == 0 {
		return "", nil
	}
	return keys[0], content[keys[0]]
}

func isJSONType(t string) bool {
	t = strings.ToLower(strings.TrimSpace(strings.Split(t, ";")[0]))
	return t == "application/json" || strings.HasSuffix(t, "+json")
}

// bodyKindOf says how the runtime encodes a request body or decodes a
// response: json, text, form, multipart or binary.
func bodyKindOf(mediaType string) string {
	t := strings.ToLower(strings.TrimSpace(strings.Split(mediaType, ";")[0]))
	switch {
	case isJSONType(t):
		return "json"
	case t == "application/x-www-form-urlencoded":
		return "form"
	case t == "multipart/form-data":
		return "multipart"
	case strings.HasPrefix(t, "text/"), strings.HasSuffix(t, "+xml"), t == "application/xml":
		return "text"
	}
	return "binary"
}

func (g *tsGen) bodyType(kind string, media *openapi3.MediaType) string {
	switch kind {
	case "json":
		return g.typeOf(media.Schema, "      ")
	case "text":
		return "string"
	case "form":
		return "Record<string, string> | URLSearchParams"
	case "multipart":
		return "FormData"
	}
	return "Blob | ArrayBuffer | Uint8Array"
}

// resultType is what a call resolves to: the success responses' bodies, or
// void when they have none. accept says how to read the body.
func (g *tsGen) resultType(op *openapi3.Operation) (string, string) {
	if op.Responses == nil {
		return "unknown", "json"
	}
	codes := op.Responses.Map()
	keys := make([]string, 0, len(codes))
	for k := range codes {
		if strings.HasPrefix(k, "2") {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	var types []string
	accept := ""
	seen := map[string]bool{}
	add := func(t string) {
		if !seen[t] {
			seen[t] = true
			types = append(types, t)
		}
	}
	for _, k := range keys {
		r := codes[k]
		if r == nil || r.Value == nil || len(r.Value.Content) == 0 {
			add("void")
			continue
		}
		mediaType, media := pickMedia(r.Value.Content)
		kind := bodyKindOf(mediaType)
		if accept == "" {
			accept = kind
		}
		switch kind {
		case "json":
			add(g.typeOf(media.Schema, "    "))
		case "text":
			add("string")
		default:
			add("Blob")
		}
	}
	if len(types) == 0 {
		return "unknown", "json"
	}
	if accept == "" {
		accept = "json"
	}
	return strings.Join(types, " | "), accept
}

// literal writes a value as a TypeScript literal.
func literal(v any) string {
	out, err := json.Marshal(v)
	if err != nil {
		return "unknown"
	}
	return string(out)
}

var identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// key writes a property name, quoted when it isn't an identifier.
func key(name string) string {
	if identifier.MatchString(name) {
		return name
	}
	return literal(name)
}

// accessor reads a property: .name, or ["x-name"].
func accessor(name string) string {
	if identifier.MatchString(name) {
		return "." + name
	}
	return "[" + literal(name) + "]"
}

func words(s string) []string {
	var out []string
	var cur []rune
	flush := func() {
		if len(cur) > 0 {
			out = append(out, string(cur))
			cur = cur[:0]
		}
	}
	runes := []rune(s)
	for i, r := range runes {
		switch {
		case !unicode.IsLetter(r) && !unicode.IsDigit(r), r > unicode.MaxASCII:
			flush()
		case unicode.IsUpper(r) && i > 0 && (unicode.IsLower(runes[i-1]) || (i+1 < len(runes) && unicode.IsLower(runes[i+1]) && unicode.IsUpper(runes[i-1]))):
			flush()
			cur = append(cur, r)
		default:
			cur = append(cur, r)
		}
	}
	flush()
	return out
}

// pascal turns "order line" or "order_line" into OrderLine.
func pascal(s string) string {
	var b strings.Builder
	for _, w := range words(s) {
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}

// camel turns "get order" or "GetOrder" into getOrder.
func camel(s string) string {
	p := pascal(s)
	if p == "" {
		return ""
	}
	return strings.ToLower(p[:1]) + p[1:]
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

func prefixed(prefix, s string) string {
	if s == "" {
		return ""
	}
	return prefix + s
}
